    private void btnCrearEquipoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearEquipoActionPerformed
        // TODO add your handling code here:
        try {
            String nombreEquipo = txtNombreEquipo.getText();
            String pais = txtPais.getText();
            String nombreMascota = txtNombreM.getText();
            String especie = txtEspecie.getText();
            String aspecto = txtAspecto.getText();
            
            equipoCreado = new Equipo(nombreEquipo, pais, nombreMascota, especie, aspecto);
            
            javax.swing.JOptionPane.showMessageDialog(this, "Equipo y Mascota base creados correctamente.");
        } catch(NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al crear el equipo");
        }
    
    }//GEN-LAST:event_btnCrearEquipoActionPerformed

