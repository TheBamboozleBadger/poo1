    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
        try {
            String nombre = txtNombre.getText();
            String apellido = txtApellido.getText();
            int edad = Integer.parseInt(txtEdad.getText());
            boolean esTitular = chkEsTitular.isSelected();
            String posicion = (String) cbPosicion.getSelectedItem();
            boolean agregado = false;

            if (posicion.equals("Defensa")) {
                Defensa def = new Defensa(esTitular, nombre, apellido, edad);
                agregado = equipoActual.inscribirDefensa(def);
            } else if (posicion.equals("Portero")) {
                int golesRec = Integer.parseInt(JOptionPane.showInputDialog(this, "Ingrese goles recibidos:"));
                Portero por = new Portero(golesRec, esTitular, nombre, apellido, edad);
                agregado = equipoActual.setPortero(por);
            } else if (posicion.equals("Delantero")) {
                int goles = Integer.parseInt(JOptionPane.showInputDialog(this, "Ingrese goles anotados:"));
                Delantero del = new Delantero(goles, esTitular, nombre, apellido, edad);
                agregado = equipoActual.inscribirDelantero(del);
            } else if (posicion.equals("Mediocampista")) {
                int asistencias = Integer.parseInt(JOptionPane.showInputDialog(this, "Ingrese asistencias:"));
                Mediocampista med = new Mediocampista(asistencias, esTitular, nombre, apellido, edad);
                agregado = equipoActual.inscribirMediocampista(med);
            }

            if (agregado) {
                JOptionPane.showMessageDialog(this, posicion + " agregado exitosamente.");
                txtNombre.setText("");
                txtApellido.setText("");
                txtEdad.setText("");
                chkEsTitular.setSelected(false);
            } else {
                JOptionPane.showMessageDialog(this, "No se puede agregar. Ya se alcanzó el límite para la posición: " + posicion);
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Error: Ingrese valores numéricos válidos.");
        }
    
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnMostrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrarActionPerformed
        // TODO add your handling code here:
        if (equipoActual.tiene11Jugadores()) {
            JOptionPane.showMessageDialog(this, "¡Felicidades! El equipo cuenta con sus 11 jugadores reglamentarios.");
            equipoActual.imprimir();
            this.dispose(); 
        } else {
            int respuesta = JOptionPane.showConfirmDialog(this, 
                "El equipo aún NO tiene los 11 jugadores (1 Portero, 4 Defensas, 4 Mediocampistas, 2 Delanteros).\n¿Desea salir de todas formas?", 
                "Equipo Incompleto", JOptionPane.YES_NO_OPTION);
            
            if (respuesta == JOptionPane.YES_OPTION) {
                equipoActual.imprimir();
                this.dispose();
            }
        }
    
    }//GEN-LAST:event_btnMostrarActionPerformed

